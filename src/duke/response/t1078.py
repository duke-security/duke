"""Dry-run response planning for the T1078 Valid Accounts scenario.

``plan_t1078_response`` consumes an existing :class:`InvestigationResult`
(which itself wraps the telemetry artefact and the ``Finding`` produced
by detection) and turns it into a deterministic :class:`ResponsePlan`.
The plan correlates the finding into a *preliminary* :class:`Incident`
record — a record required so each :class:`ResponseAction` can carry an
``incident_id`` — and groups proposed, dry-run-only actions by category:
immediate containment, evidence preservation, investigation follow-up,
and recovery recommendations.

This package is deliberately plan-only. No action is ever executed: every
proposed action is ``dry_run=True``, ``requires_approval=True``, and
``status=PLANNED``, and there is no code path that contacts an identity
provider, device, network, file system, or security control. Actions are
worded as *conditional recommendations* grounded in possible valid-account
misuse, not as assertions that a compromise or exfiltration occurred.
"""

from uuid import UUID, uuid5

from duke.core import (
    Entity,
    Finding,
    Incident,
    IncidentStatus,
    ResponseAction,
    ResponseRisk,
    ResponseStatus,
)
from duke.investigation import InvestigationResult
from duke.response.plan import (
    ResponseActionGroup,
    ResponseCategory,
    ResponsePlan,
)
from duke.telemetry import TelemetryArtefact

# Deterministic namespace so incident and action identifiers are
# repeatable for the same finding, mirroring the stable IDs used by
# simulation, detection, and investigation.
_INCIDENT_NAMESPACE = UUID("1078b000-0000-4000-8000-000000000000")

# Stable natural identifiers of the synthetic entities the T1078 plan
# targets. They match the entities generated by ``simulation.t1078``.
_ACCOUNT_IDENTIFIER = "alex.morgan@example.lab"
_UNFAMILIAR_DEVICE_IDENTIFIER = "device-unknown-442"
_PRIVILEGED_SERVICE_IDENTIFIER = "privileged-access-service"
_EXTERNAL_DESTINATION_IDENTIFIER = "203.0.113.80:443"

_SUSPECTED_MISUSE = (
    "consistent with possible valid-account misuse (MITRE ATT&CK T1078), "
    "not a confirmed compromise"
)


def _entity_by_identifier(
    artefact: TelemetryArtefact,
    identifier: str,
) -> Entity | None:
    """Resolve an entity from the artefact by its stable identifier."""
    for entity in artefact.entities:
        if entity.identifier == identifier:
            return entity
    return None


def _build_action(
    incident: Incident,
    finding: Finding,
    name: str,
    purpose: str,
    verification: str,
    risk: ResponseRisk,
    *,
    target: Entity | None,
    supports_rollback: bool,
    rollback_guidance: str | None,
) -> ResponseAction:
    """Construct one deterministic, dry-run-only proposed action."""
    return ResponseAction(
        id=uuid5(_INCIDENT_NAMESPACE, f"{incident.id}:{name}"),
        created_at=finding.created_at,
        incident_id=incident.id,
        target_entity_id=target.id if target is not None else None,
        name=name,
        purpose=purpose,
        risk=risk,
        requires_approval=True,
        dry_run=True,
        status=ResponseStatus.PLANNED,
        verification_guidance=verification,
        supports_rollback=supports_rollback,
        rollback_guidance=rollback_guidance,
    )


def _containment_actions(
    incident: Incident,
    finding: Finding,
    account: Entity | None,
    device: Entity | None,
) -> tuple[ResponseAction, ...]:
    """Proposed immediate-containment actions (conditional recommendations)."""
    return (
        _build_action(
            incident,
            finding,
            name="disable-account",
            purpose=(
                "If the behaviour is " + _SUSPECTED_MISUSE + ", suspend the "
                "account to stop further activity while it is verified. "
                "This is a recommendation to evaluate, not an assertion "
                "that the account was compromised."
            ),
            verification=(
                "Confirm whether the account can no longer authenticate and "
                "record downstream service impact before any approval."
            ),
            risk=ResponseRisk.HIGH,
            target=account,
            supports_rollback=True,
            rollback_guidance=(
                "Re-enable the account only after ownership and access "
                "safety are verified."
            ),
        ),
        _build_action(
            incident,
            finding,
            name="revoke-active-sessions",
            purpose=(
                "If the behaviour is " + _SUSPECTED_MISUSE + ", invalidate "
                "the account's active sessions so an unfamiliar device "
                "cannot remain logged in. Revoked sessions cannot be "
                "restored; this does not undo access permanently."
            ),
            verification=(
                "Confirm that no active sessions remain for the account on "
                "the unfamiliar device."
            ),
            risk=ResponseRisk.MEDIUM,
            target=account,
            supports_rollback=False,
            rollback_guidance=None,
        ),
        _build_action(
            incident,
            finding,
            name="deny-unfamiliar-device",
            purpose=(
                "If the behaviour is " + _SUSPECTED_MISUSE + ", deny "
                "authentication from the unfamiliar device pending "
                "verification of its ownership."
            ),
            verification=(
                "Confirm the unfamiliar device can no longer authenticate "
                "to the account."
            ),
            risk=ResponseRisk.MEDIUM,
            target=device,
            supports_rollback=True,
            rollback_guidance=(
                "Re-allow the device only after device ownership and "
                "security posture are verified."
            ),
        ),
    )


def _evidence_actions(
    incident: Incident,
    finding: Finding,
) -> tuple[ResponseAction, ...]:
    """Proposed evidence-preservation action."""
    return (
        _build_action(
            incident,
            finding,
            name="preserve-telemetry-artefact",
            purpose=(
                "Retain an immutable copy and a recorded hash of the "
                "exported telemetry artefact so the supporting evidence "
                "cannot be altered before investigation concludes."
            ),
            verification=(
                "Confirm a verified copy and its digest are recorded and "
                "readable."
            ),
            risk=ResponseRisk.LOW,
            target=None,
            supports_rollback=False,
            rollback_guidance=None,
        ),
    )


def _investigation_actions(
    incident: Incident,
    finding: Finding,
    account: Entity | None,
    service: Entity | None,
    destination: Entity | None,
) -> tuple[ResponseAction, ...]:
    """Proposed investigation follow-up actions."""
    return (
        _build_action(
            incident,
            finding,
            name="confirm-account-ownership",
            purpose=(
                "Engage the account owner to determine whether they "
                "performed the new-context login and follow-on behaviours. "
                "Reviewing this evidence changes no system state."
            ),
            verification=(
                "Record the owner's response and whether it confirms or "
                "refutes the possible-misuse hypothesis."
            ),
            risk=ResponseRisk.LOW,
            target=account,
            supports_rollback=False,
            rollback_guidance=None,
        ),
        _build_action(
            incident,
            finding,
            name="review-privileged-access-grant",
            purpose=(
                "Review whether the requested privileged access was granted "
                "and whether it persists. Review alone makes no change; "
                "this is not a claim that the request succeeded."
            ),
            verification=(
                "Determine whether the requested role was granted and, if "
                "so, whether an independent revocation is warranted."
            ),
            risk=ResponseRisk.MEDIUM,
            target=service,
            supports_rollback=False,
            rollback_guidance=None,
        ),
        _build_action(
            incident,
            finding,
            name="assess-exfiltration-risk",
            purpose=(
                "Correlate the observed outbound connection and archive "
                "against egress evidence to determine whether restricted "
                "data actually left. This analyses risk; it does not assume "
                "data was exfiltrated."
            ),
            verification=(
                "Document definitively whether any bytes left the "
                "environment and reconcile that with the restricted-file "
                "and archive evidence."
            ),
            risk=ResponseRisk.LOW,
            target=destination,
            supports_rollback=False,
            rollback_guidance=None,
        ),
    )


def _recovery_actions(
    incident: Incident,
    finding: Finding,
    account: Entity | None,
) -> tuple[ResponseAction, ...]:
    """Proposed recovery recommendations (conditional)."""
    return (
        _build_action(
            incident,
            finding,
            name="require-mfa-reauthentication",
            purpose=(
                "Require MFA re-authentication from a known device before "
                "restoring access, but only if the account is determined to "
                "have been misused. Never weaken baseline MFA requirements."
            ),
            verification=(
                "Confirm the account owner can re-authenticate with MFA "
                "from a verified device."
            ),
            risk=ResponseRisk.MEDIUM,
            target=account,
            supports_rollback=True,
            rollback_guidance=(
                "After explicit review, restore the previous access policy "
                "only if doing so does not lower baseline MFA requirements."
            ),
        ),
        _build_action(
            incident,
            finding,
            name="rotate-account-credentials",
            purpose=(
                "Rotate the account's credentials only if misuse is "
                "established and ownership is verified. Never restore prior "
                "potentially exposed credentials."
            ),
            verification=(
                "Confirm the owner can authenticate with new credentials "
                "and that the prior credentials no longer work."
            ),
            risk=ResponseRisk.HIGH,
            target=account,
            supports_rollback=False,
            rollback_guidance=None,
        ),
    )


def plan_t1078_response(
    artefact: TelemetryArtefact,
    result: InvestigationResult,
) -> ResponsePlan:
    """Build a deterministic, dry-run-only response plan from an investigation.

    The plan correlates ``result.finding`` into a preliminary ``Incident``
    (solely to give each ``ResponseAction`` an ``incident_id``) and
    proposes actions grouped by category. The incident is a deterministic
    correlation record, not a confirmation of compromise, exfiltration, or
    a final incident report.
    """
    finding = result.finding
    incident = Incident(
        id=uuid5(_INCIDENT_NAMESPACE, f"incident:{finding.id}"),
        opened_at=finding.created_at,
        updated_at=finding.created_at,
        title="Preliminary T1078 valid-account misuse response",
        summary=(
            "Preliminary correlation record grouping the T1078 finding for "
            "response planning. It records correlation only; impact and "
            "account state are not asserted."
        ),
        status=IncidentStatus.OPEN,
        severity=finding.severity,
        finding_ids=[finding.id],
        affected_entity_ids=[entity.id for entity in result.involved_entities],
    )

    account = _entity_by_identifier(artefact, _ACCOUNT_IDENTIFIER)
    device = _entity_by_identifier(artefact, _UNFAMILIAR_DEVICE_IDENTIFIER)
    service = _entity_by_identifier(artefact, _PRIVILEGED_SERVICE_IDENTIFIER)
    destination = _entity_by_identifier(artefact, _EXTERNAL_DESTINATION_IDENTIFIER)

    groups = (
        ResponseActionGroup(
            category=ResponseCategory.CONTAINMENT,
            actions=_containment_actions(incident, finding, account, device),
        ),
        ResponseActionGroup(
            category=ResponseCategory.EVIDENCE_PRESERVATION,
            actions=_evidence_actions(incident, finding),
        ),
        ResponseActionGroup(
            category=ResponseCategory.INVESTIGATION_FOLLOWUP,
            actions=_investigation_actions(
                incident, finding, account, service, destination
            ),
        ),
        ResponseActionGroup(
            category=ResponseCategory.RECOVERY,
            actions=_recovery_actions(incident, finding, account),
        ),
    )

    return ResponsePlan(incident=incident, finding=finding, groups=groups)
